// Smooth discrete mouse-wheel input without interfering with trackpads,
// zoom gestures, touch scrolling, or scrollable elements such as dialogs.
export function setupSmoothScroll() {
  const motion = window.matchMedia('(prefers-reduced-motion: reduce)')
  let target = window.scrollY
  let frame = null
  let lastTime = null

  function cancel() {
    if (frame !== null) cancelAnimationFrame(frame)
    frame = null
    lastTime = null
    document.documentElement.classList.remove('wheel-scrolling')
    target = window.scrollY
  }

  function animate(time) {
    const distance = target - window.scrollY
    if (Math.abs(distance) < 0.5) {
      window.scrollTo(0, target)
      frame = null
      lastTime = null
      document.documentElement.classList.remove('wheel-scrolling')
      return
    }
    const elapsed = lastTime === null ? 16.67 : Math.min(time - lastTime, 50)
    lastTime = time
    const factor = 1 - Math.exp(-elapsed / 110)
    window.scrollTo(0, window.scrollY + distance * factor)
    frame = requestAnimationFrame(animate)
  }

  function onWheel(event) {
    if (motion.matches || event.ctrlKey || event.metaKey || event.shiftKey || event.deltaX || !event.cancelable) return
    // Small or fractional deltas are typically generated by a trackpad.
    if (event.deltaMode === 0 && (Math.abs(event.deltaY) < 40 || !Number.isInteger(event.deltaY))) return
    for (let node = event.target instanceof Element ? event.target : null; node && node !== document.body; node = node.parentElement) {
      const style = getComputedStyle(node)
      if (/(auto|scroll)/.test(style.overflowY) && node.scrollHeight > node.clientHeight) return
    }
    event.preventDefault()
    document.documentElement.classList.add('wheel-scrolling')
    const delta = event.deltaY * (event.deltaMode === 1 ? 16 : event.deltaMode === 2 ? window.innerHeight : 1)
    const max = Math.max(0, document.documentElement.scrollHeight - window.innerHeight)
    target = Math.max(0, Math.min(max, (frame === null ? window.scrollY : target) + delta))
    if (frame === null) frame = requestAnimationFrame(animate)
  }

  window.addEventListener('wheel', onWheel, { passive: false })
  window.addEventListener('touchstart', cancel, { passive: true })
  window.addEventListener('keydown', cancel)
  window.addEventListener('pointerdown', cancel)
  motion.addEventListener('change', cancel)
  return () => {
    cancel()
    window.removeEventListener('wheel', onWheel)
    window.removeEventListener('touchstart', cancel)
    window.removeEventListener('keydown', cancel)
    window.removeEventListener('pointerdown', cancel)
    motion.removeEventListener('change', cancel)
  }
}
